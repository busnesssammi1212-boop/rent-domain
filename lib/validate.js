export const PLAN_SECONDS = [1800, 2400, 3600, 86400, 604800, 2592000];
export const METHODS = ['BKASH', 'NAGAD', 'ROCKET', 'CRYPTO'];
export const clean = (s, max) => String(s ?? '').replace(/[\u0000-\u001f\u007f]/g, '').trim().slice(0, max);
export const isUuid = (s) => /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(s));
export const isEmail = (s) => /^[^\s@]{1,64}@[^\s@]{1,255}\.[^\s@]{2,}$/.test(s);
export const isPhone = (s) => /^\+?[0-9]{8,15}$/.test(String(s).replace(/[\s-]/g, ''));
export const isRef = (s) => /^RX-[A-Z0-9]{5}-[A-Z0-9]{5}$/.test(String(s));
export const isTxnId = (s) => /^[A-Za-z0-9]{6,40}$/.test(s);
export const isTxHash = (s) => /^(0x)?[A-Fa-f0-9]{64}$/.test(s) || /^[A-Za-z0-9]{32,100}$/.test(s);
export const isDomain = (s) => /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$/.test(s);
